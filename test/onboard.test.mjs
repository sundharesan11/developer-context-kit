test("re-onboarding retires the prior client profile by default and keeps user records byte-identical", async (t) => {
  const s = await committedProject(t);
  const prior = await autoProfile(s);
  const user = await addRecord(s.roots, draftFor("acme", "acme.atlas", { requestId: "req_userfact001" }), { now });
  const path = join(s.dataRoot, "scopes/acme/projects/acme.atlas/records", user.recordId);
  const before = await Promise.all([readFile(join(path, "body.md")), readFile(join(path, "record.json"))]);
  const { plan, receipt } = await reonboard(s, { requestId: "req_reonboard01" });
  assert.ok(plan.retire.some((r) => r.id === prior.id && r.recordHash === prior.recordHash));
  assert.deepEqual(plan.retire.map((r) => r.id), plan.retire.map((r) => r.id).sort());
  assert.ok(!plan.retire.some((r) => r.id === user.recordId));
  const records = await snapshot(s);
  assert.equal(records.find((r) => r.id === prior.id).effective, "superseded");
  assert.deepEqual(records.find((r) => r.id === prior.id).supersededBy, [receipt.bundles[0].id]);
  assert.equal(records.find((r) => r.id === user.recordId).effective, "observed");
  assert.deepEqual((await profiles(s)).map((r) => r.id), [receipt.bundles[0].id]);
  assert.deepEqual(await Promise.all([readFile(join(path, "body.md")), readFile(join(path, "record.json"))]), before);
});
